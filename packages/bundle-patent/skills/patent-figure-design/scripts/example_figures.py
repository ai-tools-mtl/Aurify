# -*- coding: utf-8 -*-
"""示例：用 wireframe_lib 直绘专利线框图（竖排流程图 + 分层架构图 + 机制原理图三种最常用范式）。
运行：python example_figures.py  → 在本目录生成 example-flow.png / example-arch.png / example-mech.png
布局范式、字号层级与留白硬值见 SKILL.md「代码直绘通路」；成品照常过 subagent 视觉验收。"""
import os

from wireframe_lib import begin, box, container, line, label, save

HERE = os.path.dirname(os.path.abspath(__file__))


def example_flow():
    """竖排流程图：输入容器 → S1 → S2 → S3 → S4，右侧存储列，左侧自环回退与虚线反馈"""
    img, d = begin(1300, 930)
    # 顶部输入容器（标题占顶部约 60px，子框从 y=110 起）
    container(d, 300, 40, 900, 250, "多源输入数据", 26)
    box(d, 320, 110, 590, 165, ["101 卫星影像"], 20)
    box(d, 610, 110, 880, 165, ["102 无人机影像"], 20)
    box(d, 320, 175, 590, 235, ["103 地面监测数据"], 20)
    box(d, 610, 175, 880, 235, ["104 文件数据"], 20)
    line(d, [(600, 250), (600, 290)])

    # 主流程链（每框高 ~110，间距 40）
    box(d, 300, 290, 900, 400, ["S1 数据接入与画像构建", "接入模块201：元数据提取·模板路由"], 22, 6)
    box(d, 960, 305, 1220, 385, ["301 原始库"], 20)
    line(d, [(900, 345), (960, 345)])
    line(d, [(600, 400), (600, 440)])

    box(d, 300, 440, 900, 550, ["S2 处理流程生成", "主控模块202：人工确认 / 自动执行"], 22, 6)
    line(d, [(600, 550), (600, 590)])

    box(d, 300, 590, 900, 700, ["S3 清洗与标准化", "处理模块203：清洗·标准化·质量评分"], 22, 6)
    box(d, 960, 605, 1220, 685, ["302 标准库"], 20)
    line(d, [(900, 645), (960, 645)])
    # 质量不达标回退自环：从框侧绕出 ≥40px 再绕回
    line(d, [(300, 670), (255, 670), (255, 620), (300, 620)])
    label(d, (185, 645), "不达标回退", 16, "mm")

    # 虚线反馈：S3 → S2（沿最左空白通道竖直绕行，不穿任何元素）
    line(d, [(300, 590), (40, 590), (40, 495), (300, 495)], dashed=True)
    label(d, (55, 470), "处理参数反馈", 17, "lm")

    line(d, [(600, 700), (600, 740)])
    box(d, 300, 740, 900, 880, ["S4 成果输出"], 22)
    save(img, os.path.join(HERE, "example-flow.png"))


def example_arch():
    """分层架构图：三横层 + 层间竖直箭头 + 右侧虚线反哺（走容器内侧空白通道，不压边框）"""
    img, d = begin(1400, 900)
    container(d, 40, 40, 1360, 230, "数据源层", 24)
    for i, t in enumerate(["101 卫星影像", "102 无人机影像", "103 地面监测", "104 文件"]):
        x = 80 + i * 320
        box(d, x, 110, x + 290, 195, [t], 19)
        line(d, [(x + 145, 195), (x + 145, 230)])

    container(d, 40, 230, 1360, 560, "协作层", 24)
    box(d, 540, 285, 860, 355, ["主控模块202", "流程生成·调度"], 19, 4)
    # 总线：主控 → 水平总线 → 各模块（干路无箭头，箭头只落各支路末梢）
    line(d, [(700, 355), (700, 390)], arrow=False)
    line(d, [(200, 390), (1200, 390)], arrow=False)
    for i, (name, num) in enumerate([("接入", "201"), ("处理", "203"), ("融合", "204"), ("分析", "205")]):
        x = 100 + i * 280
        line(d, [(x + 100, 390), (x + 100, 420)])
        box(d, x, 420, x + 200, 510, [name + "模块", num], 19, 4)
    # 虚线反哺：分析模块右缘中点引出 → 容器内侧空白通道上行 → 主控右缘中点
    line(d, [(1140, 465), (1320, 465), (1320, 320), (860, 320)], dashed=True)
    label(d, (1080, 298), "知识反哺", 17, "mm")

    line(d, [(700, 560), (700, 600)])
    container(d, 40, 600, 1360, 790, "存储层", 24)
    for i, t in enumerate(["301 原始库", "302 标准库", "303 融合库", "304 分析库"]):
        x = 80 + i * 320
        box(d, x, 665, x + 290, 745, [t], 19)
        if i:
            line(d, [(x - 30, 705), (x, 705)])
    save(img, os.path.join(HERE, "example-arch.png"))


def example_mechanism():
    """机制原理图：三列（封装侧 → 发布产物槽位解剖 → 消费/恢复侧），公式编号入框。

    布局要点：中列槽位与正文发布清单逐项对应；K1 只走属性通路、K2 只走身份通路，
    双路汇入合成框；正文未写明来源的参数（MPK/P/UK_S）只入框内文字、不画来源连线。"""
    img, d = begin(1440, 800)
    # 三列容器
    container(d, 40, 60, 580, 640, "加密侧（资源提供方）", 24)
    container(d, 650, 140, 950, 660, "资源包（发布产物）", 24)
    container(d, 1010, 60, 1400, 740, "解密侧（设备端）", 24)

    # 封装列：拆分 → 属性/身份两条通路
    box(d, 100, 120, 540, 200, ["密钥拆分（式2）", "随机生成 K1、K2，合成 K = H0(K1‖K2)"], 20, 5)
    box(d, 100, 250, 440, 340, ["属性份额封装（属性侧通路）", "CT_ABE = FAME.Encrypt(MPK, P, K1)"], 20, 5)
    box(d, 100, 420, 540, 590, ["身份份额掩蔽（身份侧通路）", "选身份锚点 ρ，共享锚点 L = ρ·g1", "W_d = K2 ⊕ H2(ρ·PK_d)（式3）"], 20, 5)
    line(d, [(200, 200), (200, 250)])
    label(d, (215, 228), "K1", 17, "lm")
    line(d, [(100, 155), (60, 155), (60, 455), (100, 455)])
    label(d, (72, 390), "K2", 17, "lm")

    # 产物槽位列（与正文发布清单逐项对应）
    box(d, 670, 285, 930, 345, ["属性密文 CT_ABE"], 20)
    box(d, 670, 375, 930, 435, ["共享身份锚点 L"], 20)
    box(d, 670, 465, 930, 525, ["授权列表 {W_d}"], 20)
    box(d, 670, 555, 930, 615, ["密文 C = Enc_K(M)"], 20)
    line(d, [(440, 315), (670, 315)])
    line(d, [(540, 460), (600, 460), (600, 405), (670, 405)])
    line(d, [(540, 545), (620, 545), (620, 495), (670, 495)])

    # 消费列：双门 → 合成
    box(d, 1050, 150, 1360, 350, ["属性门", "属性集 S 满足策略 P 时，", "UK_S 对 CT_ABE 运行 FAME 解密，恢复 K1"], 20, 5)
    box(d, 1050, 375, 1360, 525, ["身份门", "Z_d = sk_d·L（式4）", "K2 = W_d ⊕ H2(Z_d)（式5）"], 20, 5)
    box(d, 1050, 610, 1360, 700, ["双门合成", "K = H0(K1‖K2)", "用 K 解密 C 得资源明文 M"], 20, 5)
    line(d, [(930, 315), (1050, 315)])
    line(d, [(930, 405), (1050, 405)])
    line(d, [(930, 495), (1050, 495)])
    line(d, [(1360, 250), (1380, 250), (1380, 655), (1360, 655)])
    label(d, (1372, 568), "K1", 17, "rm")
    line(d, [(1205, 525), (1205, 610)])
    label(d, (1220, 568), "K2", 17, "lm")

    save(img, os.path.join(HERE, "example-mech.png"))


if __name__ == "__main__":
    example_flow()
    example_arch()
    example_mechanism()
    print("saved:", os.path.join(HERE, "example-flow.png"), os.path.join(HERE, "example-arch.png"),
          os.path.join(HERE, "example-mech.png"))
